import { basename, join, relative, sep } from 'node:path';
import { listMd, writeDoc } from './hubfs';

export function rebuildIndex(hubDir: string, relDir: string, title: string): void {
  const dir = join(hubDir, relDir);
  const groups = new Map<string, string[]>();
  for (const file of listMd(dir)) {
    if (basename(file) === '_index.md') continue;
    const inDir = relative(dir, file);
    const group = inDir.includes(sep) ? inDir.split(sep)[0] : '(root)';
    const link = relative(hubDir, file).split(sep).join('/').replace(/\.md$/, '');
    groups.set(group, [...(groups.get(group) ?? []), link]);
  }
  const lines = [`# ${title}`, '', '_Generated by RixFlow. Do not edit._', ''];
  for (const group of [...groups.keys()].sort()) {
    lines.push(`## ${group}`);
    for (const link of groups.get(group)!.sort().reverse()) lines.push(`- [[${link}]]`);
    lines.push('');
  }
  writeDoc(join(dir, '_index.md'), { type: 'index', generated: true }, lines.join('\n'));
}
