import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import YAML from 'yaml';
import { Git, commitAll } from './git';
import { writeDoc, writeGuarded } from './hubfs';
import type { SiteDef, TeamMember } from './team';
import { HubError, assertName, assertSiteCode } from './types';

const README = `# Team hub

Knowledge vault and inbox for the team's Claude Code sessions.
Managed only by the RixFlow plugin. Do not edit by hand. Opening it in Obsidian to read is fine.

- shared/   team knowledge (decisions, per-site notes)
- people/   each person's notes, session summaries, checkpoints, handovers
- inbox/    messages between people's Claude sessions
- config/   team roster and website → folder mapping

Everything here is visible to the whole team.
`;

// Files that tools such as Obsidian, Finder and Explorer drop into a vault, plus our own temp files.
export const HUB_GITIGNORE = ['.obsidian/', '.trash/', '.DS_Store', 'Thumbs.db', '*.tmp-*'];

const BOOTSTRAP_PATHS = ['.gitignore', 'README.md', 'config', 'shared', 'people', 'inbox'];

const FOLDER = /^[A-Za-z0-9][A-Za-z0-9._-]*$/;

function validate(members: TeamMember[], sites: Record<string, SiteDef>): void {
  const seen = new Set<string>();
  for (const m of members) {
    assertName(m.name);
    if (m.role !== 'dev' && m.role !== 'pm') throw new HubError('BAD_CONFIG', `member ${m.name}: role must be dev or pm`);
    if (seen.has(m.name)) throw new HubError('BAD_CONFIG', `duplicate member: ${m.name}`);
    seen.add(m.name);
  }
  for (const [code, site] of Object.entries(sites)) {
    assertSiteCode(code);
    if (typeof site?.folder !== 'string' || !FOLDER.test(site.folder) || site.folder.includes('..')) {
      throw new HubError('BAD_CONFIG', `site ${code}: folder must be one safe path segment`);
    }
  }
}

export async function bootstrapHub(
  dir: string,
  members: TeamMember[],
  sites: Record<string, SiteDef>,
  env: NodeJS.ProcessEnv = process.env,
): Promise<void> {
  validate(members, sites);
  if (existsSync(join(dir, '.git'))) throw new HubError('ALREADY_EXISTS', `${dir} is already a git repository`);
  const putRaw = (rel: string, text: string) => {
    mkdirSync(dirname(join(dir, rel)), { recursive: true });
    writeFileSync(join(dir, rel), text);
  };
  const putDoc = (rel: string, type: string, body: string) => writeDoc(join(dir, rel), { type, generated: true }, body);
  // Config first: its presence marks the hub root for the guarded writes below.
  putRaw('config/team.yml', YAML.stringify({ members }));
  putRaw('config/sites.yml', YAML.stringify({ sites }));
  putRaw('.gitignore', `${HUB_GITIGNORE.join('\n')}\n`);
  putDoc('README.md', 'readme', README);
  putDoc('shared/_index.md', 'index', '# Shared knowledge\n\n_Generated by RixFlow. Do not edit._\n');
  putRaw('shared/decisions/.gitkeep', '');
  for (const m of members) {
    putDoc(`people/${m.name}/_index.md`, 'index', `# ${m.name}\n\n_Generated by RixFlow. Do not edit._\n`);
    putRaw(`inbox/${m.name}/.gitkeep`, '');
  }
  const git = new Git(dir, env);
  await git.run(['init', '-q', '-b', 'main']);
  await commitAll(git, 'chore: bootstrap team hub', BOOTSTRAP_PATHS);
}

// Adds any missing HUB_GITIGNORE entries to the root .gitignore of an existing clone, keeping its
// other lines. Returns true when the file changed; committing and pushing it is the caller's job
// (hub init does it through persistHub, under the hub lock).
export function mergeHubGitignore(dir: string): boolean {
  const path = join(dir, '.gitignore');
  const current = existsSync(path) ? readFileSync(path, 'utf8') : '';
  const have = new Set(current.split(/\r?\n/).map((l) => l.trim()));
  const missing = HUB_GITIGNORE.filter((e) => !have.has(e));
  if (missing.length === 0) return false;
  const base = current === '' || current.endsWith('\n') ? current : `${current}\n`;
  writeGuarded(path, `${base}${missing.join('\n')}\n`);
  return true;
}
